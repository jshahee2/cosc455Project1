//! contrains the lexical analyzer for the lolcode compiler


use std::collections::HashMap;
use std::process;


use crate::traits::Compiler;
use crate::traits::SyntaxAnalyzer;

/// stores source code and keeps track of tokens and their line numbers and then builds final html
pub struct LolCompiler {
    
    /// the whole source file as characters
    pub chars: Vec<char>, 

    /// index of the next character to read
    pub pos: usize,     
    
    /// current line number (for error messages)
    pub line: usize,      

    /// the token being built right now
    pub lexeme: String,   


    // filled by the lexer, read by the parser

    /// every token in order
    pub tokens: Vec<String>, 

    /// the line number of each token
    pub lines: Vec<usize>,   

    /// index of the token the parser is looking at
    pub tok_pos: usize,      

    /// the token the parser is looking at
    pub current: String,     


    // used by the parser

    /// one map of variables per open block
    pub scopes: Vec<HashMap<String, String>>, 

    /// the HTML
    pub html: String,                         
}

impl LolCompiler {
    /// creates a new compiler
    pub fn new() -> LolCompiler {
        LolCompiler {
            chars: Vec::new(),
            pos: 0,
            line: 1,
            lexeme: String::new(),
            tokens: Vec::new(),
            lines: Vec::new(),
            tok_pos: 0,
            current: String::new(),
            scopes: Vec::new(),
            html: String::new(),
        }
    }

    /// returns a copy of the HTML generated by the compiler
    pub fn get_html(&self) -> String {
        self.html.clone()
    }

    /// Run the lexer over the whole source and store every token.
    pub fn load_tokens(&mut self, source: &str) {
        self.chars = source.chars().collect();
        self.pos = 0;
        self.line = 1;
        self.tokens.clear();
        self.lines.clear();
        self.html.clear();
        self.scopes.clear();
        loop {
            let tok = self.next_token();
            if tok.is_empty() {
                break;        // end of the file
            }
            self.tokens.push(tok);
            self.lines.push(self.line);
        }
    }
}

/// implements the Compiler trait for LolCompiler
impl Compiler for LolCompiler {
    /// compiles the source code into HTML
    fn compile(&mut self, source: &str) {
        self.load_tokens(source);
        self.parse();
    }

    /// returns the next token from the input
    fn next_token(&mut self) -> String {
        self.read_token()
    }

    /// parses the tokens and generates HTML
    fn parse(&mut self) {
        self.start_parsing();
        if let Err(message) = self.parse_lolcode() {
            eprintln!("{}", message);
            process::exit(1);
        }
    }

    /// returns copy of current token
    fn current_token(&self) -> String {
        self.current.clone()
    }

    /// updates current token being looked at by the parser
    fn set_current_token(&mut self, tok: String) {
        self.current = tok;
    }
}
